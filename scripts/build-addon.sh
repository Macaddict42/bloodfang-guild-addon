#!/bin/sh
# Builds <ADDON_NAME>-<version>.zip containing <ADDON_NAME>/ (SPEC §18b). Reproducible: fixed file order,
# timestamps from SOURCE_DATE_EPOCH (the tagged commit's time), no extra zip metadata.
set -eu
VERSION="$1"; NAME="${ADDON_NAME:?set ADDON_NAME}"; TITLE="${ADDON_TITLE:-$NAME}"; INTERFACE="${ADDON_INTERFACE:-16001}"
case "$VERSION" in *[!0-9.]*|"") echo "bad version"; exit 2;; esac
: "${SOURCE_DATE_EPOCH:=$(git log -1 --format=%ct)}"
out=dist; rm -rf "$out"; mkdir -p "$out/$NAME"
cp -r addon/Libs addon/*.lua "$out/$NAME/"
# Slash commands (build config, like the name): ADDON_SLASH is the short command without the slash; the long one is
# the addon name in lower case. Generated into Config.lua, which the TOC loads first.
SHORT="${ADDON_SLASH:?set ADDON_SLASH (short slash command, no leading /)}"
LONG=$(printf '%s' "$NAME" | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9')
for c in "$SHORT" "$LONG"; do case "$c" in ""|*[!a-z0-9]*) echo "bad slash command '$c'"; exit 2;; esac; done
[ "$SHORT" != "$LONG" ] || { echo "ADDON_SLASH must differ from the addon name"; exit 2; }
printf -- '-- Generated by scripts/build-addon.sh from the build config. Do not edit.\nlocal _, ns = ...\nns.slash = { "/%s", "/%s" }\n' "$SHORT" "$LONG" > "$out/$NAME/Config.lua"
sed -e "s/@INTERFACE@/$INTERFACE/" -e "s/@ADDON_TITLE@/$TITLE/" -e "s/@VERSION@/$VERSION/" -e "s/@ADDON_NAME@/$NAME/" addon/Addon.toc.template > "$out/$NAME/$NAME.toc"
# Addon list icon (## IconTexture) from the guild's logo, supplied by the build config (ADDON_ICON: a local PNG path or an
# https URL, e.g. the site's header logo). Converted to a 64x64 32-bit uncompressed TGA, which the client loads.
if [ -n "${ADDON_ICON:-}" ]; then
  src="$ADDON_ICON"
  case "$src" in https://*) curl -fsSL "$src" -o "$out/icon-src.png"; src="$out/icon-src.png";; esac
  python3 scripts/make-icon.py "$src" "$out/$NAME/Icon.tga"
  rm -f "$out/icon-src.png"
else
  echo "ADDON_ICON not set: building without an addon list icon"
  sed -i '/^## IconTexture:/d' "$out/$NAME/$NAME.toc"
fi
cp LICENSE "$out/$NAME/"
cd "$out"
python3 - "$NAME" "$NAME-$VERSION.zip" "$SOURCE_DATE_EPOCH" <<'PY'
import os, sys, time, zipfile
name, out, epoch = sys.argv[1], sys.argv[2], max(int(sys.argv[3]), 315532800)
stamp = time.gmtime(epoch)[:6]
files = sorted(os.path.join(d, f) for d, _, fs in os.walk(name) for f in fs)
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for f in files:
        i = zipfile.ZipInfo(f.replace(os.sep, "/"), stamp); i.external_attr = 0o644 << 16; i.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(i, open(f, "rb").read())
PY
sha256sum "$NAME-$VERSION.zip" > "$NAME-$VERSION.zip.sha256"
cat "$NAME-$VERSION.zip.sha256"
